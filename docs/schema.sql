-- Enable UUID generation (already on in Supabase; run once on plain PG)
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ── 1. USERS ─────────────────────────────────────────────────
-- One row per employee. Supabase Auth user id can be used as the PK
-- (replace UUID default with auth.uid() in RLS policies).
CREATE TABLE users (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email        TEXT UNIQUE NOT NULL,
  display_name TEXT NOT NULL,                -- shown in the UI ("David", "Rian")
  role         TEXT NOT NULL
                 CHECK (role IN ('staff','ap','spv','finance')),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ── 2. FILES ─────────────────────────────────────────────────
-- Uploaded via Supabase Storage / S3; only the metadata row lives here.
CREATE TABLE files (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name         TEXT NOT NULL,
  storage_path TEXT NOT NULL,   -- e.g. "invoices/2025/TK-1234-invoice.pdf"
  mime_type    TEXT,
  size_bytes   INTEGER,
  uploaded_by  UUID REFERENCES users(id) ON DELETE SET NULL,
  uploaded_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ── 3. RESERVATIONS ──────────────────────────────────────────
-- Core booking record. `display_id` (TK-XXXX) is generated by trigger.
CREATE SEQUENCE reservation_seq START 1000;

CREATE TABLE reservations (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  display_id   TEXT UNIQUE NOT NULL
                 DEFAULT 'TK-' || LPAD(nextval('reservation_seq')::TEXT, 4, '0'),
  staff_id     UUID NOT NULL REFERENCES users(id),

  -- Booking details
  company      TEXT NOT NULL,
  product      TEXT NOT NULL
                 CHECK (product IN ('intl','dom','kai','whoosh')),
  vendor       TEXT NOT NULL,
  carrier      TEXT NOT NULL DEFAULT '',
  pnr          TEXT NOT NULL,
  route        TEXT NOT NULL DEFAULT '',
  travel_date  TIMESTAMPTZ NOT NULL,
  ttl          TIMESTAMPTZ,              -- time limit / ticketing deadline
  amount       INTEGER NOT NULL,         -- in IDR (whole rupiah)
  pay_method   TEXT NOT NULL
                 CHECK (pay_method IN ('credit','ap')),
  urgent       BOOLEAN NOT NULL DEFAULT FALSE,

  -- Derived stage (kept explicit for easy filtering/indexing)
  -- Values: waitap | revise | toissue | toinvoice | done
  stage        TEXT NOT NULL DEFAULT 'toissue'
                 CHECK (stage IN ('waitap','revise','toissue','toinvoice','done')),

  -- Issued
  ticket_no    TEXT,
  issued_at    TIMESTAMPTZ,

  -- Invoiced (→ archive)
  invoice_no   TEXT,
  invoiced_at  TIMESTAMPTZ,

  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ── 4. PASSENGERS ────────────────────────────────────────────
-- One row per passenger name on a reservation.
CREATE TABLE passengers (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  reservation_id UUID NOT NULL REFERENCES reservations(id) ON DELETE CASCADE,
  name           TEXT NOT NULL,
  position       SMALLINT NOT NULL DEFAULT 0  -- display order
);

-- ── 5. AP PAYMENT REQUESTS ───────────────────────────────────
-- Created when pay_method = 'ap'. One-to-one with reservation.
CREATE TABLE ap_requests (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  reservation_id UUID UNIQUE NOT NULL REFERENCES reservations(id) ON DELETE CASCADE,
  status         TEXT NOT NULL DEFAULT 'waiting'
                   CHECK (status IN ('waiting','paid','revise')),

  -- Bank details for transfer
  bank           TEXT NOT NULL,
  acct           TEXT NOT NULL,
  acct_name      TEXT NOT NULL,

  -- Attached files
  invoice_file_id UUID REFERENCES files(id) ON DELETE SET NULL,
  proof_file_id   UUID REFERENCES files(id) ON DELETE SET NULL,

  -- Revision note (set when AP returns to staff)
  revise_note    TEXT,

  requested_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  paid_at        TIMESTAMPTZ,
  paid_by        UUID REFERENCES users(id) ON DELETE SET NULL
);

-- ── 6. AUDIT LOG ─────────────────────────────────────────────
-- Append-only; one row per action. Mirrors the in-app LogEntry.
CREATE TABLE reservation_logs (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  reservation_id UUID NOT NULL REFERENCES reservations(id) ON DELETE CASCADE,
  actor_id       UUID REFERENCES users(id) ON DELETE SET NULL,
  actor_name     TEXT NOT NULL,           -- snapshot of display_name at log time
  message        TEXT NOT NULL,
  is_post_payment BOOLEAN NOT NULL DEFAULT FALSE,  -- ⚠ flag for edits after payment
  logged_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================
-- INDEXES
-- ============================================================
CREATE INDEX idx_reservations_staff     ON reservations(staff_id);
CREATE INDEX idx_reservations_stage     ON reservations(stage);
CREATE INDEX idx_reservations_urgent    ON reservations(urgent) WHERE urgent = TRUE;
CREATE INDEX idx_reservations_created   ON reservations(created_at DESC);
CREATE INDEX idx_passengers_reservation ON passengers(reservation_id);
CREATE INDEX idx_ap_requests_status     ON ap_requests(status);
CREATE INDEX idx_logs_reservation       ON reservation_logs(reservation_id, logged_at DESC);

-- ============================================================
-- UPDATED_AT TRIGGER (auto-updates updated_at on every row change)
-- ============================================================
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_reservations_updated_at
  BEFORE UPDATE ON reservations
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_users_updated_at
  BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ============================================================
-- STAGE SYNC TRIGGER
-- Keeps `stage` column consistent whenever key columns change.
-- ============================================================
CREATE OR REPLACE FUNCTION sync_reservation_stage()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.invoiced_at IS NOT NULL THEN
    NEW.stage := 'done';
  ELSIF NEW.issued_at IS NOT NULL THEN
    NEW.stage := 'toinvoice';
  ELSIF NEW.pay_method = 'credit' THEN
    NEW.stage := 'toissue';
  ELSE
    -- ap path: stage is set explicitly by AP actions; default stays 'waitap'
    NULL;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_sync_stage
  BEFORE INSERT OR UPDATE OF issued_at, invoiced_at ON reservations
  FOR EACH ROW EXECUTE FUNCTION sync_reservation_stage();

